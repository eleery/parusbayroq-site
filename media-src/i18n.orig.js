// ===== LANGUAGE ENGINE =====
let currentLang = localStorage.getItem('lang') || 'ru';

function t(key) {
  return TRANSLATIONS[currentLang][key] || TRANSLATIONS['ru'][key] || key;
}

function movePill() {
  const switcher = document.getElementById('lang-switcher');
  const pill = document.getElementById('lang-pill');
  const activeBtn = switcher && switcher.querySelector('.lang-btn--active');
  if (!pill || !activeBtn || !switcher) return;
  const switcherRect = switcher.getBoundingClientRect();
  const btnRect = activeBtn.getBoundingClientRect();
  pill.style.width = btnRect.width + 'px';
  pill.style.transform = `translateX(${btnRect.left - switcherRect.left - 3}px)`;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val !== undefined) el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-ph'));
  });
  // Translate select options with data-i18n-opt
  document.querySelectorAll('[data-i18n-opt]').forEach(el => {
    const key = el.getAttribute('data-i18n-opt');
    const val = t(key);
    if (val) el.textContent = val;
  });
  // Update lang switcher active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('lang-btn--active', btn.getAttribute('data-lang') === currentLang);
  });
  movePill();
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  if (typeof window.repopulateCalcSizes === 'function') {
    window.repopulateCalcSizes();
  }
}

// Init on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
  // Init pill instantly (no animation on first load)
  const pill = document.getElementById('lang-pill');
  if (pill) {
    pill.style.transition = 'none';
    movePill();
    // Enable transition after initial position is set
    requestAnimationFrame(() => {
      requestAnimationFrame(() => {
        pill.style.transition = '';
      });
    });
  }
});
